ALTER TABLE raza ADD COLUMN IF NOT EXISTS grupo_fci SMALLINT;
ALTER TABLE raza ADD COLUMN IF NOT EXISTS numero_fci INT;
ALTER TABLE raza ADD COLUMN IF NOT EXISTS origen VARCHAR(80);
ALTER TABLE raza ADD COLUMN IF NOT EXISTS tamano VARCHAR(12);
ALTER TABLE raza ADD COLUMN IF NOT EXISTS reconocimiento_fci VARCHAR(12);
ALTER TABLE raza ADD COLUMN IF NOT EXISTS potencialmente_peligrosa BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_raza_grupo_fci') THEN
    ALTER TABLE raza ADD CONSTRAINT ck_raza_grupo_fci CHECK (grupo_fci IS NULL OR grupo_fci BETWEEN 1 AND 10);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_raza_tamano') THEN
    ALTER TABLE raza ADD CONSTRAINT ck_raza_tamano CHECK (tamano IS NULL OR tamano IN ('MINI','PEQUENO','MEDIANO','GRANDE','GIGANTE'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_raza_reconocimiento_fci') THEN
    ALTER TABLE raza ADD CONSTRAINT ck_raza_reconocimiento_fci CHECK (reconocimiento_fci IS NULL OR reconocimiento_fci IN ('DEFINITIVO','PROVISIONAL','NO_FCI'));
  END IF;
END
$$;

